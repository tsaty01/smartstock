package com.smartstock.app.ui.theme

import androidx.compose.foundation.background
import androidx.compose.runtime.Composable
import androidx.compose.runtime.remember
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.drawBehind
import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.ImageBitmap
import androidx.compose.ui.graphics.ImageShader
import androidx.compose.ui.graphics.ShaderBrush
import androidx.compose.ui.graphics.TileMode
import androidx.compose.ui.res.imageResource
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp
import com.smartstock.app.R

/** Seamless cream paper tile (generated by tools/paper_texture.py). */
@Composable
fun Modifier.paper(dark: Boolean = false): Modifier {
	val tile = ImageBitmap.imageResource(R.drawable.paper)
	val brush = remember(tile) { ShaderBrush(ImageShader(tile, TileMode.Repeated, TileMode.Repeated)) }
	return if (dark) background(Color(0xFF141E17)).drawBehind { drawRect(brush, alpha = 0.045f) }
	else background(brush)
}

private val RuleGreen = Color(0x55729A79)
private val MarginRed = Color(0x99B2704B)

/** Bill-book page: paper with faint green rules and a warm double margin. */
@Composable
fun Modifier.billPage(lineSpacing: Dp = 28.dp, margin: Dp = 28.dp): Modifier = paper().drawBehind {
	val step = lineSpacing.toPx()
	val stroke = 1.dp.toPx()
	var y = step
	while (y < size.height) {
		drawLine(RuleGreen, Offset(0f, y), Offset(size.width, y), stroke)
		y += step
	}
	val x = margin.toPx()
	drawLine(MarginRed, Offset(x, 0f), Offset(x, size.height), stroke)
	drawLine(MarginRed, Offset(x + 3.dp.toPx(), 0f), Offset(x + 3.dp.toPx(), size.height), stroke)
}
